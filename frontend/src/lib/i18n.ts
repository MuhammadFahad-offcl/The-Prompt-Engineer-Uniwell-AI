const dictionaries: Record<Language, Partial<Record<TKey, string>>> = { en, roman_urdu }

export function translate(lang: Language, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[lang]?.[key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export interface I18nValue {
  lang: Language
  t: (key: TKey, vars?: Record<string, string | number>) => string
}

export const I18nContext = createContext<I18nValue>({
  lang: 'en',
  t: (key, vars) => translate('en', key, vars),
})

export function useT(): I18nValue {
  return useContext(I18nContext)
}
